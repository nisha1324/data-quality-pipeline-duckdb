"""Write check results as a CSV and a Markdown report."""
from pathlib import Path
import csv

from dq.engine import Result

STATUS_ICON = {"pass": "✅ pass", "warn": "⚠️ warn", "error": "❌ error"}


def md_table(headers: list[str], rows: list[list]) -> str:
    def cell(v) -> str:
        return "" if v is None else str(v).replace("|", "\\|").replace("\n", " ")
    lines = ["| " + " | ".join(headers) + " |",
             "|" + "|".join("---" for _ in headers) + "|"]
    lines += ["| " + " | ".join(cell(v) for v in row) + " |" for row in rows]
    return "\n".join(lines)


def write_csv(results: list[Result], path: Path) -> None:
    with path.open("w", newline="") as f:
        w = csv.writer(f)
        w.writerow(["check_id", "table", "dimension", "severity", "status",
                    "failing", "checked", "fail_pct"])
        for r in results:
            c = r.check
            w.writerow([c.id, c.table or "", c.dimension, c.severity, r.status,
                        r.failing, r.checked, f"{r.fail_pct:.3f}"])


def write_markdown(results: list[Result], params: dict, source: dict,
                   path: Path) -> None:
    counts = source["files"]["counts"]
    sensors = source["files"]["sensors"]
    n = {s: sum(r.status == s for r in results) for s in STATUS_ICON}
    out = [
        "# Data-quality report",
        "",
        f"Snapshot `{params['snapshot']}`: counts processed by the portal at "
        f"{params['reference_ts']} (Melbourne time); "
        f"{counts['rows']:,} hourly count rows, {sensors['rows']:,} sensors.",
        "",
        f"**{len(results)} checks: {n['pass']} pass, {n['warn']} warn, "
        f"{n['error']} error.**",
        "",
        "Generated by `scripts/run_checks.py` from `checks/pedestrian.yml`. "
        "Failing = records the check's query returns (for `unique` checks, "
        "every row that shares its key).",
        "",
        "## Summary",
        "",
        md_table(
            ["Check", "Dimension", "Severity", "Status", "Failing", "Checked", "Fail %"],
            [[f"`{r.check.id}`", r.check.dimension, r.check.severity,
              STATUS_ICON[r.status], f"{r.failing:,}", f"{r.checked:,}",
              f"{r.fail_pct:.2f}%"] for r in results],
        ),
        "",
        "## Failures and warnings",
        "",
    ]
    failed = [r for r in results if r.failing]
    if not failed:
        out.append("None.")
    for r in failed:
        out += [
            f"### `{r.check.id}` ({STATUS_ICON[r.status]})",
            "",
            r.check.description,
            "",
            f"{r.failing:,} failing of {r.checked:,} checked ({r.fail_pct:.2f}%)."
            + (f" Tolerance: {r.check.tolerance_pct:g}%." if r.check.tolerance_pct else ""),
            "",
            f"First {len(r.sample)} failing records:",
            "",
            md_table(list(r.sample[0].keys()),
                     [list(row.values()) for row in r.sample]),
            "",
            "<details><summary>Query</summary>",
            "",
            "```sql",
            r.fail_sql,
            "```",
            "",
            "</details>",
            "",
        ]
    path.write_text("\n".join(out).rstrip() + "\n")
