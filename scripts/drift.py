"""Part 4: compare two snapshots of the feed. Did history change?

Usage:
    python scripts/drift.py                       # the two newest snapshots in data/raw/
    python scripts/drift.py --old data/raw/2026-10-18T1539Z --new data/raw/2026-10-20T1538Z
    python scripts/drift.py --fail-on error       # exit 1 if any check errors

Outputs (in results/): DRIFT.md and drift_results.csv.
"""
from pathlib import Path
import argparse
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from dq import drift  # noqa: E402
from dq.engine import load_suite  # noqa: E402
from dq.load import RAW  # noqa: E402
from dq.report import failure_sections, md_table, summary_table, write_csv  # noqa: E402

RESULTS = ROOT / "results"


def pct(new: float, old: float) -> str:
    return f"{100.0 * (new - old) / old:+.1f}%" if old else "n/a"


def write_markdown(con, results, skipped, params, path: Path) -> None:
    n = {s: sum(r.status == s for r in results) for s in ("pass", "warn", "error")}
    sides = con.execute("""
        select 'old', (select count(*) from old_counts), (select count(*) from old_sensors)
        union all
        select 'new', (select count(*) from new_counts), (select count(*) from new_sensors)
    """).fetchall()
    rows = {side: (c, s) for side, c, s in sides}
    out = [
        "# Snapshot drift report",
        "",
        f"Older snapshot `{params['old_snapshot']}` vs newer `{params['new_snapshot']}`, "
        f"processed by the portal {params['hours_apart']:g} hours apart. "
        "Generated by `scripts/drift.py` from `checks/drift.yml`.",
        "",
        f"**{len(results)} checks: {n['pass']} pass, {n['warn']} warn, {n['error']} error"
        + (f", {len(skipped)} not run" if skipped else "") + ".**",
        "",
        md_table(["Snapshot", "First day", "Newest day", "Count rows", "Sensors"],
                 [[f"`{params[f'{side}_snapshot']}`", params[f"{side}_first"],
                   params[f"{side}_last"], f"{rows[side][0]:,}", f"{rows[side][1]:,}"]
                  for side in ("old", "new")]),
        "",
        "## Summary",
        "",
        summary_table(results),
        "",
    ]
    if skipped:
        out += [
            "Not run, because the schema changed and a row-by-row comparison would "
            "fail rather than report: " + ", ".join(f"`{c.id}`" for c in skipped) + ".",
            "",
        ]
    else:
        settled = con.execute("""
            select count(*), count(*) filter (where old_count = new_count),
                   min(sensing_date), max(sensing_date)
            from overlap_rows where part = 'settled'
        """).fetchone()
        days = drift.daily_drift(con)
        out += [
            "## Days both snapshots cover",
            "",
            f"Settled days ({settled[2]} to {settled[3]}): {settled[1]:,} of "
            f"{settled[0]:,} sensor-hours are identical in both snapshots.",
            "",
            "Days with any difference:",
            "",
            md_table(["Day", "Part", "Rows (old → new)", "Pedestrians (old → new)",
                      "Change", "Appeared", "Disappeared", "Count changed"],
                     [[d, part, f"{o_r:,} → {n_r:,}", f"{o_p:,} → {n_p:,}", pct(n_p, o_p),
                       f"{a:,}", f"{gone:,}", f"{ch:,}"]
                      for d, part, o_r, n_r, o_p, n_p, a, gone, ch in days])
            if days else "None.",
            "",
            f"## The day that was still being filled ({params['old_last']})",
            "",
            "Each hour the older snapshot had already published on its newest day: "
            "as first published, and in the newer snapshot.",
            "",
            md_table(["Hour", "Sensors first published", "Pedestrians first published",
                      "Counts revised since", "Same sensors now", "Sensors now",
                      "Pedestrians now", "First published vs now"],
                     [[f"{h:02d}:00", f"{fr:,}", f"{fp:,}", f"{rev:,}", f"{same:,}",
                       f"{nr:,}", f"{npd:,}", pct(fp, npd)]
                      for h, fr, fp, rev, same, nr, npd in drift.first_vs_final(con)]),
            "",
        ]
    out += ["## Failures and warnings", "", *failure_sections(results)]
    path.write_text("\n".join(out).rstrip() + "\n")


def main() -> int:
    parser = argparse.ArgumentParser(description="Compare two snapshots of the feed.")
    parser.add_argument("--old", type=Path, help="older snapshot folder")
    parser.add_argument("--new", type=Path, help="newer snapshot folder")
    parser.add_argument("--suite", type=Path, default=ROOT / "checks" / "drift.yml")
    parser.add_argument("--fail-on", choices=["warn", "error"],
                        help="exit with status 1 if any check ends at this level or worse")
    args = parser.parse_args()

    if bool(args.old) != bool(args.new):
        parser.error("give both --old and --new, or neither")
    old, new = (args.old, args.new) if args.old else drift.snapshot_pair(RAW)
    con, params = drift.load_pair(old, new)
    results, skipped = drift.run_drift(con, load_suite(args.suite), params)

    RESULTS.mkdir(exist_ok=True)
    write_csv(results, RESULTS / "drift_results.csv")
    write_markdown(con, results, skipped, params, RESULTS / "DRIFT.md")

    for r in results:
        print(f"{r.status:5}  {r.check.id:32} {r.failing:>9,} / {r.checked:,}")
    for c in skipped:
        print(f"skip   {c.id}")
    levels = {"warn": ("warn", "error"), "error": ("error",)}
    if args.fail_on and any(r.status in levels[args.fail_on] for r in results):
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
