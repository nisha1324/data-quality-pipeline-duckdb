"""Part 3: the trust scorecard. Which reports can the business use today?

Runs the check suite and the Part 2 gap estimate on a snapshot, computes the
measures each report depends on, and gives every report in
checks/reports.yml a verdict: trusted, use with caveat, or don't use.

Usage:
    python scripts/scorecard.py                  # newest snapshot in data/raw/
    python scripts/scorecard.py --snapshot data/raw/2026-10-18T1539Z

Outputs (in results/): SCORECARD.md and scorecard.csv (one row per report
and rule).
"""
from pathlib import Path
import argparse
import csv
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from dq import completeness as cp  # noqa: E402
from dq import scorecard as sc  # noqa: E402
from dq.engine import load_suite, run_suite  # noqa: E402
from dq.load import latest_snapshot, load_snapshot  # noqa: E402
from dq.report import md_table  # noqa: E402

RESULTS = ROOT / "results"


def write_csv(verdicts: list, path: Path) -> None:
    with path.open("w", newline="") as f:
        w = csv.writer(f)
        w.writerow(["report_id", "report", "verdict", "rule_kind", "rule_ref",
                    "threshold", "rule_verdict", "observed", "fired"])
        for v in verdicts:
            for o in v.outcomes:
                r = o.rule
                w.writerow([v.report.id, v.report.name, v.verdict, r.kind, r.ref,
                            r.threshold(), r.verdict, o.value, o.fired])


def write_markdown(verdicts: list, notes: list, params: dict, windows: dict,
                   path: Path) -> None:
    n = {k: sum(v.verdict == k for v in verdicts) for k in sc.VERDICTS}
    out = [
        "# Trust scorecard",
        "",
        f"Snapshot `{params['snapshot']}` (counts {params['first_date']} to "
        f"{params['last_date']}). Generated by `scripts/scorecard.py` from "
        "`checks/reports.yml`.",
        "",
        f"**{len(verdicts)} reports: {n['trusted']} trusted, {n['caveat']} use with caveat, "
        f"{n['dont_use']} don't use.** The verdict is for the report as usually built: "
        "plain sums and averages over the published rows.",
        "",
        "Windows for this snapshot: "
        + "; ".join(f"{k.replace('_', ' ')} {a}" + (f" to {b}" if b != a else "")
                    for k, (a, b) in windows.items()) + ".",
        "",
        md_table(["Report", "Verdict", "Why", "What to do instead"],
                 [[v.report.name, sc.LABEL[v.verdict],
                   "; ".join(dict.fromkeys(o.reason for o in v.fired
                                           if o.rule.verdict == v.verdict)) or "all rules pass",
                   "; ".join(dict.fromkeys(o.rule.fix for o in v.fired
                                           if o.rule.verdict == v.verdict and o.rule.fix))
                   or "use as is"]
                  for v in verdicts]),
        "",
        "## Notes",
        "",
        *[f"- {note}" for note in notes],
        "",
        "## Every rule, by report",
        "",
    ]
    for v in verdicts:
        out += [
            f"### {v.report.name}: {sc.LABEL[v.verdict]}",
            "",
            f"*{v.report.question}* Window: {v.report.window}.",
            "",
        ]
        if v.fired:
            out += [f"- **{sc.LABEL[o.rule.verdict]}:** {o.reason}."
                    + (f" *Instead:* {o.rule.fix}." if o.rule.fix else "")
                    for o in v.fired] + [""]
        out += [
            md_table(["Rule", "Fires when", "Gives", "Observed", "Fired"],
                     [[f"`{o.rule.ref}`", o.rule.threshold(), o.rule.verdict, o.value,
                       "yes" if o.fired else "no"] for o in v.outcomes]),
            "",
        ]
    path.write_text("\n".join(out).rstrip() + "\n")


def main() -> int:
    parser = argparse.ArgumentParser(description="Trust scorecard per business report.")
    parser.add_argument("--snapshot", type=Path, help="snapshot folder (default: newest)")
    parser.add_argument("--suite", type=Path, default=ROOT / "checks" / "pedestrian.yml")
    parser.add_argument("--reports", type=Path, default=ROOT / "checks" / "reports.yml")
    args = parser.parse_args()

    snapshot = args.snapshot or latest_snapshot()
    con, params, _ = load_snapshot(snapshot)
    checks = load_suite(args.suite)
    results = {r.check.id: r for r in run_suite(con, checks, params)}
    cp.build_gaps(con)
    cp.estimate_gaps(con)
    measures = sc.compute_measures(con)
    reports, notes = sc.load_reports(args.reports, set(results), set(measures))
    verdicts = sc.evaluate(reports, results, measures)

    RESULTS.mkdir(exist_ok=True)
    write_csv(verdicts, RESULTS / "scorecard.csv")
    write_markdown(verdicts, notes, params, sc.windows(con), RESULTS / "SCORECARD.md")
    for v in verdicts:
        print(f"{v.verdict:9} {v.report.name}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
