"""Part 4b: the daily gate. Did anything new go wrong today?

Runs the check suite on a snapshot and, if a previous snapshot is given, the
drift checks against it. Errors covered by checks/known_issues.yml are
accepted; any other error fails the gate (exit status 1). Also gives the
day's trust verdict for every report in checks/reports.yml.

Usage:
    python scripts/gate.py                         # newest snapshot, no drift
    python scripts/gate.py --previous data/raw/2026-10-18T1539Z
    python scripts/gate.py --snapshot data/raw/2026-10-20T1538Z \\
        --previous data/raw/2026-10-18T1539Z

Output (in results/, or the folder given with --out): GATE.md, a one-page
summary that the scheduled workflow also shows as its job summary.
"""
from pathlib import Path
import argparse
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from dq import completeness as cp  # noqa: E402
from dq import drift  # noqa: E402
from dq import gate  # noqa: E402
from dq import scorecard as sc  # noqa: E402
from dq.engine import load_suite, run_suite  # noqa: E402
from dq.load import latest_snapshot, load_snapshot  # noqa: E402
from dq.report import md_table  # noqa: E402

RESULTS = ROOT / "results"
CHECKS = ROOT / "checks"


def plural(n: int, word: str) -> str:
    return f"{n} {word}" + ("" if n == 1 else "s")


def suite_row(name: str, rows: list[gate.GateRow], results: list) -> list:
    n = {s: sum(r.status == s for r in results) for s in ("pass", "warn", "error")}
    k = {o: sum(row.suite == name and row.outcome == o for row in rows)
         for o in ("known", "blocking")}
    return [f"`{name}`", len(results), n["pass"], n["warn"], n["error"],
            k["known"], k["blocking"]]


def write_markdown(params: dict, previous: str | None, suites: dict, rows: list,
                   verdicts: list, path: Path) -> None:
    blocking = [r for r in rows if r.outcome == "blocking"]
    known = [r for r in rows if r.outcome == "known"]
    resolved = [r for r in rows if r.outcome == "resolved"]
    if blocking:
        headline = (f"**❌ Fail: {plural(len(blocking), 'error check')} with failures "
                    "that no known issue covers.**")
    else:
        headline = "**✅ Pass: no new errors.**"
    if known:
        headline += f" {plural(len(known), 'known issue')} accepted."
    compared = (f"compared with the previous snapshot `{previous}`" if previous else
                "with no previous snapshot to compare, so the drift checks did not run "
                "(a first run, or the portal hasn't published since the last run)")
    out = [
        "# Daily data-quality gate",
        "",
        f"Snapshot `{params['snapshot']}` (counts {params['first_date']} to "
        f"{params['last_date']}), {compared}. Generated by `scripts/gate.py` with "
        "`checks/known_issues.yml`.",
        "",
        headline,
        "",
        md_table(["Suite", "Checks", "Pass", "Warn", "Error", "Error, known issue",
                  "Error, blocking"],
                 [suite_row(name, rows, results) for name, results in suites.items()]),
        "",
    ]
    if blocking:
        out += [
            "## Blocking errors",
            "",
            md_table(["Suite", "Check", "Failing", "Not covered by a known issue",
                      "What it checks"],
                     [[f"`{r.suite}`", f"`{r.result.check.id}`", f"{r.result.failing:,}",
                       f"{r.unaccepted:,}", r.result.check.description]
                      for r in blocking]),
            "",
        ]
    if known:
        out += [
            "## Known issues accepted today",
            "",
            md_table(["Check", "Failing", "Accepted where", "Why", "Owner", "Since"],
                     [[f"`{r.result.check.id}`", f"{r.result.failing:,}",
                       f"`{r.issue.accept_where}`", r.issue.reason, r.issue.owner,
                       r.issue.since] for r in known]),
            "",
        ]
    if resolved:
        out += [
            "## Known issues that no longer fire",
            "",
            "These checks pass now. Remove them from `checks/known_issues.yml`, so a "
            "return of the problem is caught.",
            "",
            md_table(["Check", "Since"],
                     [[f"`{r.result.check.id}`", r.issue.since] for r in resolved]),
            "",
        ]
    out += [
        "## Which reports to use today",
        "",
        "From the trust scorecard (`checks/reports.yml`); `scripts/scorecard.py` "
        "gives the reasons and what to do instead.",
        "",
        md_table(["Report", "Verdict"],
                 [[v.report.name, sc.LABEL[v.verdict]] for v in verdicts]),
    ]
    path.write_text("\n".join(out).rstrip() + "\n")


def main() -> int:
    parser = argparse.ArgumentParser(description="Daily data-quality gate.")
    parser.add_argument("--snapshot", type=Path, help="snapshot folder (default: newest)")
    parser.add_argument("--previous", type=Path,
                        help="previous snapshot folder; if given, the drift checks run too")
    parser.add_argument("--known", type=Path, default=CHECKS / "known_issues.yml")
    parser.add_argument("--out", type=Path, default=RESULTS,
                        help="folder for GATE.md (default: results/)")
    args = parser.parse_args()

    snapshot = args.snapshot or latest_snapshot()
    checks = load_suite(CHECKS / "pedestrian.yml")
    drift_checks = load_suite(CHECKS / "drift.yml")
    issues = gate.load_known_issues(args.known, checks + drift_checks)

    con, params, _ = load_snapshot(snapshot)
    results = run_suite(con, checks, params)
    rows = gate.evaluate(con, "pedestrian.yml", results, issues)
    suites = {"pedestrian.yml": results}

    cp.build_gaps(con)
    cp.estimate_gaps(con)
    measures = sc.compute_measures(con)
    by_id = {r.check.id: r for r in results}
    reports, _ = sc.load_reports(CHECKS / "reports.yml", set(by_id), set(measures))
    verdicts = sc.evaluate(reports, by_id, measures)

    previous = None
    if args.previous:
        pcon, pparams = drift.load_pair(args.previous, snapshot)
        presults, skipped = drift.run_drift(pcon, drift_checks, pparams)
        rows += gate.evaluate(pcon, "drift.yml", presults, issues)
        suites["drift.yml"] = presults
        previous = pparams["old_snapshot"]

    args.out.mkdir(parents=True, exist_ok=True)
    write_markdown(params, previous, suites, rows, verdicts, args.out / "GATE.md")
    for r in rows:
        print(f"{r.outcome:9} {r.suite:15} {r.result.check.id:32} "
              f"{r.result.failing:>9,} failing, {r.unaccepted:,} not covered")
    ok = gate.passed(rows)
    print("gate: pass" if ok else "gate: FAIL")
    return 0 if ok else 1


if __name__ == "__main__":
    sys.exit(main())
